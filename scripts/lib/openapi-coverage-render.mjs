/**
 * Render docs/COVERAGE.md markdown (maintainer/CI only).
 */
import { CoverageError } from './openapi-coverage-errors.mjs';

const ALLOWED_BUCKETS = new Set(['covered', 'deferred', 'out-of-scope', 'gap']);

/**
 * Escape dynamic markdown table cell values (CodeQL js/incomplete-sanitization).
 *
 * @param {string} value
 * @returns {string}
 */
function escapeMarkdownTableCell(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/\|/g, '\\|');
}

/**
 * @param {Array<{ action: string, client: string, openapi: string, bucket: string, reason: string }>} rows
 * @returns {string}
 */
export function renderCoverageMarkdown(rows) {
  const counts = {
    covered: 0,
    deferred: 0,
    'out-of-scope': 0,
    gap: 0,
  };

  for (const row of rows) {
    if (!ALLOWED_BUCKETS.has(row.bucket)) {
      throw new CoverageError(
        `Invalid bucket "${row.bucket}" for ${row.action}`,
        'Invalid coverage bucket in generated report',
      );
    }
    counts[row.bucket] += 1;
  }

  const lines = [
    '# OpenAPI Coverage — awesome-coolify-mcp',
    '',
    'Generated action-to-API review for the pinned Coolify v4.1.2 specification.',
    '',
    '> [!IMPORTANT]',
    '> Edit the [coverage map and overrides](./OPENAPI.md#coverage-map-maintenance), not this file.',
    '> Regenerate with `pnpm run openapi:coverage`; verify with `pnpm run openapi:coverage -- --check`.',
    '',
    '[OpenAPI maintenance](./OPENAPI.md) · [Setup guide](./en/setup.md)',
    '',
    '## Summary',
    '',
    '| bucket | count |',
    '| --- | ---: |',
    `| covered | ${counts.covered} |`,
    `| deferred | ${counts.deferred} |`,
    `| out-of-scope | ${counts['out-of-scope']} |`,
    `| gap | ${counts.gap} |`,
    '',
    '## Bucket definitions',
    '',
    '- **covered** — action, client export, and pinned OpenAPI operation are linked.',
    '- **deferred** — future work has an explicit reason and is not a current feature promise.',
    '- **out-of-scope** — deliberately outside MCP behavior or unavailable through REST.',
    '- **gap** — mapping needs maintainer review; it does not by itself mean shipped behavior is broken.',
    '',
    '## Actions',
    '',
    '| tool.action | client | openapi | bucket | reason |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const row of rows) {
    const action = escapeMarkdownTableCell(row.action);
    const client = row.client ? escapeMarkdownTableCell(row.client) : '—';
    const openapi = row.openapi ? escapeMarkdownTableCell(row.openapi) : '—';
    const reason = row.reason ? escapeMarkdownTableCell(row.reason) : '—';
    lines.push(
      `| \`${action}\` | ${client} | ${openapi} | ${row.bucket} | ${reason} |`,
    );
  }

  lines.push(
    '',
    '---',
    '',
    '_Generated by `pnpm run openapi:coverage`. See [maintenance and provenance](./OPENAPI.md)._',
    '',
  );

  return `${lines.join('\n')}\n`;
}
