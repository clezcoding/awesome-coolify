/**
 * Render docs/COVERAGE.md markdown (maintainer/CI only).
 */

/**
 * @param {Array<{ action: string, client: string, openapi: string, bucket: string, reason: string }>} rows
 * @returns {string}
 */
export function renderCoverageMarkdown(rows) {
  const counts = {
    covered: 0,
    deferred: 0,
    'out-of-scope': 0,
    gap: 0,
  };

  for (const row of rows) {
    if (row.bucket in counts) counts[row.bucket] += 1;
  }

  const lines = [
    '# OpenAPI Coverage — awesome-coolify-mcp',
    '',
    '> Committed gap report — regenerate with `pnpm run openapi:coverage`.',
    '',
    '## Summary',
    '',
    '| bucket | count |',
    '| --- | ---: |',
    `| covered | ${counts.covered} |`,
    `| deferred | ${counts.deferred} |`,
    `| out-of-scope | ${counts['out-of-scope']} |`,
    `| gap | ${counts.gap} |`,
    '',
    '## Actions',
    '',
    '| tool.action | client | openapi | bucket | reason |',
    '| --- | --- | --- | --- | --- |',
  ];

  for (const row of rows) {
    const reason = row.reason.replace(/\|/g, '\\|');
    lines.push(
      `| \`${row.action}\` | ${row.client || '—'} | ${row.openapi || '—'} | ${row.bucket} | ${reason || '—'} |`,
    );
  }

  lines.push('', '---', '', '_Generated by `pnpm run openapi:coverage`._', '');

  return `${lines.join('\n')}\n`;
}
